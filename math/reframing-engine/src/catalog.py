"""Frozen distant-object catalog.

Assignment rule (written before known-answer scoring):
- `addresses` = barrier classes this object has been used to attack in
  *some* standard theorem, not specifically the five test problems.
- `solves_case_tags` = types of *easier* statements already theorems
  for this object.
- `year_available` = first year a working mathematician could name the
  object as a tool (not the year it solved a millennium problem).
- Maturity: theorem_rich / mixed / speculative / heuristic.
- The catalog is intentionally broad. It includes objects that will
  score badly on the five tests. That is the point.

Do not add an object just because a historical winner used it, and do
not delete one because it dilutes a winner. Frozen 2026-10-10.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class DistantObject:
    id: str
    name: str
    area: str
    year_available: int
    maturity: str  # theorem_rich | mixed | speculative | heuristic
    addresses: tuple[str, ...]
    solves_case_tags: tuple[str, ...]
    templates_ok: tuple[str, ...]
    needs_attachment: bool
    code_shadow: str
    one_line: str


def _o(**kwargs) -> DistantObject:
    return DistantObject(**kwargs)


